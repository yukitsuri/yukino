fn embed_dir(name: &str, dir: &Path, code: &mut String) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files = Vec::new();
    collect_files(dir, dir, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let mut hasher = blake3::Hasher::new();
    for (rel_path, abs_path) in &files {
        hasher.update(rel_path.as_bytes());
        let content = fs::read(abs_path).expect("failed to read embedded file");
        hasher.update(&content);
    }
    let hash = hasher.finalize().to_hex().to_string();

    let _ = writeln!(code, "pub const {name}_SOURCE_HASH: &str = \"{hash}\";\n");
    let _ = writeln!(code, "pub const {name}_FILES: &[(&str, &[u8])] = &[");
    for (rel_path, abs_path) in &files {
        let abs_str = abs_path.to_string_lossy().replace('\\', "/");
        let _ = writeln!(code, "    (\"{rel_path}\", include_bytes!(\"{abs_str}\")),");
    }
    code.push_str("];\n\n");
}

fn collect_files(base_dir: &Path, current_dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(current_dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        println!("cargo:rerun-if-changed={}", path.display());
        if path.is_dir() {
            if path.file_name().is_some_and(|n| n == "target" || n == ".git") {
                continue;
            }
            collect_files(base_dir, &path, files);
        } else if path.is_file()
            && let Ok(rel) = path.strip_prefix(base_dir)
        {
            let rel_str = rel.to_string_lossy().replace('\\', "/");
            files.push((rel_str, path));
        }
    }
}
