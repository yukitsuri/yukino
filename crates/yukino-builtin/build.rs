use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use std::process::Command;

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR not set"));
    let runtime_dir = manifest_dir.join("../../builtin/runtime");
    let stdlib_dir = manifest_dir.join("../../builtin/stdlib");
    let macrosdk_dir = manifest_dir.join("../../builtin/macrosdk");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR not set"));

    println!("cargo:rerun-if-env-changed=YUKINO_RELEASEBUILD");
    let is_release = env::var("YUKINO_RELEASEBUILD").map_or_else(
        |_| env::var("PROFILE").map_or(false, |p| p == "release"),
        |v| v == "1",
    );
    let target = env::var("TARGET").expect("TARGET not set");

    let mut code = String::new();
    code.push_str("// auto-generated by build.rs\n\n");
    let _ = writeln!(code, "pub const IS_RELEASE_BUILD: bool = {is_release};");
    let _ = writeln!(code, "pub const HOST_PREBUILT_TARGET: &str = \"{target}\";\n");

    embed_dir("RUNTIME", &runtime_dir, &mut code);
    embed_dir("STDLIB", &stdlib_dir, &mut code);
    embed_dir("MACROSDK", &macrosdk_dir, &mut code);

    let rt_archive = build_host_runtime(&runtime_dir, &out_dir, &target, is_release);
    if let Some(archive_path) = rt_archive {
        let abs_str = archive_path.to_string_lossy().replace('\\', "/");
        let _ = writeln!(
            code,
            "pub const HOST_PREBUILT_RT: Option<&'static [u8]> = Some(include_bytes!(\"{abs_str}\"));"
        );
    } else {
        code.push_str("pub const HOST_PREBUILT_RT: Option<&'static [u8]> = None;\n");
    }

    let std_core_archive = build_host_stdlib_core(&stdlib_dir, &out_dir, &target, is_release);
    if let Some(archive_path) = std_core_archive {
        let abs_str = archive_path.to_string_lossy().replace('\\', "/");
        let _ = writeln!(
            code,
            "pub const HOST_PREBUILT_STD_CORE: Option<&'static [u8]> = Some(include_bytes!(\"{abs_str}\"));"
        );
    } else {
        code.push_str("pub const HOST_PREBUILT_STD_CORE: Option<&'static [u8]> = None;\n");
    }

    let macrosdk_core_archive = build_host_macrosdk_core(&macrosdk_dir, &out_dir, &target, is_release);
    if let Some(archive_path) = macrosdk_core_archive {
        let abs_str = archive_path.to_string_lossy().replace('\\', "/");
        let _ = writeln!(
            code,
            "pub const HOST_PREBUILT_MACROSDK_CORE: Option<&'static [u8]> = Some(include_bytes!(\"{abs_str}\"));"
        );
    } else {
        code.push_str("pub const HOST_PREBUILT_MACROSDK_CORE: Option<&'static [u8]> = None;\n");
    }

    code.push_str("pub const HOST_PREBUILT_STD: Option<&'static [u8]> = None;\n");

    fs::write(out_dir.join("embedded_runtime_data.rs"), code)
        .expect("failed to write embedded_runtime_data.rs");
}

fn strip_archive(archive: &Path) {
    let _ = Command::new("llvm-strip")
        .arg("--strip-debug")
        .arg(archive)
        .status()
        .or_else(|_| {
            Command::new("strip")
                .arg("--strip-debug")
                .arg(archive)
                .status()
        });
}

fn build_host_runtime(
    runtime_dir: &Path,
    out_dir: &Path,
    target: &str,
    is_release: bool,
) -> Option<PathBuf> {
    let src_lib = runtime_dir.join("src/lib.rs");
    if !src_lib.is_file() {
        return None;
    }
    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
    let out_archive = out_dir.join("libyukino_rt_host.a");

    let mut cmd = Command::new(&rustc);
    cmd.arg("--crate-name")
        .arg("yukino_rt")
        .arg("--crate-type")
        .arg("staticlib")
        .arg("--edition")
        .arg("2024");

    if is_release {
        cmd.arg("-C")
            .arg("opt-level=z")
            .arg("-C")
            .arg("codegen-units=1")
            .arg("-C")
            .arg("panic=abort")
            .arg("-C")
            .arg("strip=debuginfo");
    } else {
        cmd.arg("-C")
            .arg("opt-level=0")
            .arg("-C")
            .arg("debuginfo=2")
            .arg("-C")
            .arg("panic=abort");
    }

    cmd.arg("--target")
        .arg(target)
        .arg(&src_lib)
        .arg("-o")
        .arg(&out_archive);

    let status = cmd.status().ok()?;
    if !status.success() {
        println!("cargo:warning=failed to precompile runtime for {target}");
        return None;
    }

    if is_release && !target.contains("msvc") {
        strip_archive(&out_archive);
    }

    Some(out_archive)
}

fn build_host_stdlib_core(
    stdlib_dir: &Path,
    out_dir: &Path,
    target: &str,
    is_release: bool,
) -> Option<PathBuf> {
    let manifest_path = stdlib_dir.join("Cargo.toml");
    if !manifest_path.is_file() {
        return None;
    }
    let cargo = env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let target_dir = out_dir.join("std_core_target");
    let out_archive = out_dir.join("libyukistd_core_host.a");

    let mut cmd = Command::new(&cargo);
    cmd.env_remove("CARGO_MANIFEST_DIR")
        .env_remove("OUT_DIR")
        .env_remove("CARGO_TARGET_DIR")
        .arg("build")
        .arg("--manifest-path")
        .arg(&manifest_path)
        .arg("--target")
        .arg(target)
        .arg("--target-dir")
        .arg(&target_dir);

    if is_release {
        cmd.arg("--release");
    }

    let output = match cmd.output() {
        Ok(o) => o,
        Err(e) => {
            println!("cargo:warning=failed to spawn cargo: {e}");
            return None;
        }
    };
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        println!(
            "cargo:warning=failed to precompile stdlib core for {target}: status={}\nstdout:\n{stdout}\nstderr:\n{stderr}",
            output.status
        );
        return None;
    }

    let profile_subdir = if is_release { "release" } else { "debug" };
    let archive_name = if target.contains("msvc") {
        "yukistd_core.lib"
    } else {
        "libyukistd_core.a"
    };

    let built_archive = target_dir.join(target).join(profile_subdir).join(archive_name);
    if !built_archive.is_file() {
        println!(
            "cargo:warning=stdlib core archive not found at {}",
            built_archive.display()
        );
        return None;
    }

    if let Err(e) = fs::copy(&built_archive, &out_archive) {
        println!("cargo:warning=failed to copy stdlib core archive: {e}");
        return None;
    }

    if is_release && !target.contains("msvc") {
        strip_archive(&out_archive);
    }

    Some(out_archive)
}

